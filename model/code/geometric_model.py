# GFP_positions.csv is generated by the GFP_positions.ipynb notebook, which
# parses actual plasmid .dna sequence files to locate the LEFVTAA motif
# (GFP C-terminal tag) and computes domain-end and exit-tunnel positions.
# The last domain's exit position is capped at gene_length (= stop codon).
_pos_df = pd.read_csv(data_dir / 'GFP_positions.csv')
X_END = _pos_df['GFP_tag_position_end'].tolist()               # [590, 835, ..., 1815]
X_EXIT = _pos_df['GFP_tag_position_end_plus_exit_tunnel'].tolist()  # [640, 885, ..., 1826]
N_GFP_MAX = len(X_END)

# The last exit position is capped at gene_length (stop codon) = L_TOTAL
L_TOTAL = X_EXIT[-1]    # 1826 aa (protein + stop codon)
L_TUNNEL = 50           # Ribosome exit tunnel length (amino acids)

# Average elongation rates (aa/s) — from Harringtonine run-off assays
# on 10×HA–4×GFP(sf or uv)–2×mCherry constructs
V_SF = 3.88     # GFPfast
V_UV = 1.63     # GFPslow


