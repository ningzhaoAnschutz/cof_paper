def plot_geometric_fit(result, cell_data, save_name, label, ylim=100):
    """Plot geometric model fit with per-cell scatter and model predictions."""
    fig, ax = plt.subplots(figsize=(5, 5))

    # Categorical x positions (evenly spaced, no gap for missing constructs)
    n_vals = sorted(result['n_vals'])
    x_pos = list(range(1, len(n_vals) + 1))
    n_to_x = {n: x for n, x in zip(n_vals, x_pos)}

    obs = list(result['obs'])
    sem = list(result['sems'])
    preds = list(result['preds'])

    # Per-cell data points with jitter
    np.random.seed(42)
    for n in n_vals:
        if n in cell_data and len(cell_data[n]) > 0:
            jitter = np.random.normal(0, 0.05, len(cell_data[n]))
            ax.scatter([n_to_x[n] + j for j in jitter], cell_data[n],
                       alpha=0.35, color='darkgray', s=18, zorder=1)

    # Mean ± SEM
    ax.errorbar(x_pos, obs, yerr=sem, fmt='o', capsize=5, capthick=2,
                color='dimgray', markersize=10, label='Data (mean ± SEM)',
                zorder=3, linewidth=2)

    # Model predictions
    ax.scatter(x_pos, preds, color='red', s=200, zorder=4, marker='+',
               linewidths=3.5, label=label)

    ax.set_xlabel('Number of GFP Domains', fontsize=16)
    ax.set_ylabel('CoF Efficiency (%)', fontsize=16)
    ax.tick_params(axis='both', which='major', labelsize=14)
    ax.legend(loc='lower center', bbox_to_anchor=(0.5, 1.02), ncol=2,
              fontsize=10, frameon=True)
    ax.set_xlim(0.5, len(n_vals) + 0.5)
    ax.set_ylim(0, ylim)
    ax.set_xticks(x_pos)
    ax.set_xticklabels([str(n) for n in n_vals])

    plt.tight_layout()
    for fmt in ['png', 'svg']:
        fig.savefig(figures_dir / f'{save_name}.{fmt}', dpi=300,
                    bbox_inches='tight', facecolor='white', format=fmt)
    plt.close(fig)
    print(f"Saved: figures/{save_name}.png + .svg")


