"""
Geometric Spatial Delay Model for Co-Translational GFP Folding
==============================================================

Models co-translational folding as a spatial race along the mRNA.  Each
GFP domain requires a minimum "folding distance" (L_fold = tau_fold × v)
of continued translation after it emerges from the ribosome exit tunnel.
If the remaining transcript is shorter than this distance, the domain
cannot fold co-translationally.

Assuming ribosomes are uniformly distributed along the transcript in
steady state, the detection probability for domain i is:

    P_i = max(0, (L_total - x_fluorescent_i) / L_total)

where x_fluorescent_i = x_exit_i + L_fold.

Two fitted parameters per GFP variant:
    A        – Maximum amplitude (detection/competence fraction, %)
    tau_fold – Inherent folding time (seconds)

Inputs:
    - Per-cell CoF efficiency data from Excel (data/ directory)

Outputs:
    - Fit results and spatial constraints (CSV + JSON)
    - Model fit plots (PNG + SVG)
    - 2D parameter sensitivity heatmaps (PNG + SVG)
"""

