    # ── 3. Spatial constraints table ─────────────────────────────────────
    print("\n\n--- Spatial Constraints ---")
    print(f"{'Domain':<8} {'End (aa)':>10} {'Exit (aa)':>10} "
          f"{'Remaining (aa)':>15}")
    for i in range(N_GFP_MAX):
        remaining = L_TOTAL - X_EXIT[i]
        flag = " *** FAILS" if remaining <= 0 else ""
        print(f"GFP {i+1:<4} {X_END[i]:>10} {X_EXIT[i]:>10} "
              f"{remaining:>15}{flag}")

    for label, result in [('sfGFP', result_sf), ('GFPuv', result_uv)]:
        print(f"\n{label}: domains that can fold "
              f"(L_fold={result['L_fold']:.0f} aa):")
        for i in range(N_GFP_MAX):
            x_fl = X_EXIT[i] + result['L_fold']
            status = "✓ folds" if x_fl < L_TOTAL else "✗ runs out of mRNA"
            print(f"  GFP{i+1}: x_fluorescent = {x_fl:.0f} aa  →  {status}")

    # ── 4. Save data ─────────────────────────────────────────────────────
    # Spatial constraints CSV
    with open(data_dir / 'spatial_constraints.csv', 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['domain', 'x_end_aa', 'x_exit_aa', 'remaining_aa',
                     'sfGFP_x_fluorescent_aa', 'sfGFP_can_fold',
                     'GFPuv_x_fluorescent_aa', 'GFPuv_can_fold'])
        for i in range(N_GFP_MAX):
            x_fl_sf = X_EXIT[i] + result_sf['L_fold']
            x_fl_uv = X_EXIT[i] + result_uv['L_fold']
            w.writerow([i + 1, X_END[i], X_EXIT[i], L_TOTAL - X_EXIT[i],
                         f'{x_fl_sf:.1f}', x_fl_sf < L_TOTAL,
                         f'{x_fl_uv:.1f}', x_fl_uv < L_TOTAL])
    print(f"\nSaved: data/spatial_constraints.csv")

    # Fit results CSV
    with open(data_dir / 'fit_results.csv', 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['variant', 'v_aa_per_s', 'A_pct', 'tau_fold_s',
                     'L_fold_aa', 'r2', 'chi2'])
        for r in [result_sf, result_uv]:
            w.writerow([r['variant'], r['v'], f"{r['A']:.4f}",
                         f"{r['tau_fold']:.4f}", f"{r['L_fold']:.1f}",
                         f"{r['r2']:.4f}", f"{r['chi2']:.4f}"])
    print(f"Saved: data/fit_results.csv")

    # Predictions CSV
    with open(data_dir / 'predictions.csv', 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['variant', 'n_gfp', 'observed_pct', 'sem_pct',
                     'predicted_pct', 'residual_pct'])
        for r in [result_sf, result_uv]:
            for n, obs, sem, pred in zip(r['n_vals'], r['obs'],
                                         r['sems'], r['preds']):
                w.writerow([r['variant'], n, f"{obs:.2f}", f"{sem:.2f}",
                             f"{pred:.2f}", f"{pred - obs:.2f}"])
    print(f"Saved: data/predictions.csv")

    # JSON (full machine-readable)
    with open(data_dir / 'geometric_model_results.json', 'w') as f:
        json.dump({'sfGFP': result_sf, 'GFPuv': result_uv,
                   'geometry': {'L_total': L_TOTAL, 'L_tunnel': L_TUNNEL,
                                'N_gfp_max': N_GFP_MAX,
                                'X_END': X_END, 'X_EXIT': X_EXIT}},
                  f, indent=2)
    print(f"Saved: data/geometric_model_results.json")

    # ── 5. Plot model fits ───────────────────────────────────────────────
    plot_geometric_fit(result_sf, sf_cells, 'geometric_model_fast_fit',
                       label='Geometric Model (fast)', ylim=100)
    plot_geometric_fit(result_uv, uv_cells, 'geometric_model_slow_fit',
                       label='Geometric Model (slow)', ylim=60)

    # ── 6. Parameter sensitivity analysis ────────────────────────────────
    print("\nComputing 2D parameter sensitivity...")
    ci_results = plot_sensitivity(result_sf, result_uv,
                                   sf_means, sf_sems, uv_means, uv_sems)

    # ── 7. Save parameter estimates with 95% CIs ────────────────────────
    with open(data_dir / 'parameter_estimates_with_ci.csv', 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['variant', 'parameter', 'optimum', '95ci_low', '95ci_high'])
        for variant_key, ci in ci_results.items():
            w.writerow([variant_key, 'tau_fold (s)',
                        f"{ci['tau_fold_opt']:.1f}",
                        f"{ci['tau_fold_95ci_low']:.1f}",
                        f"{ci['tau_fold_95ci_high']:.1f}"])
            w.writerow([variant_key, 'A (%)',
                        f"{ci['A_opt']:.1f}",
                        f"{ci['A_95ci_low']:.1f}",
                        f"{ci['A_95ci_high']:.1f}"])
            w.writerow([variant_key, 'L_fold (aa)',
                        f"{ci['L_fold']:.0f}", '', ''])
            w.writerow([variant_key, 'k_e (aa/s)',
                        f"{ci['v']:.2f}", '', ''])
            w.writerow([variant_key, 'chi2',
                        f"{ci['chi2']:.2f}", '', ''])
    print(f"Saved: data/parameter_estimates_with_ci.csv")

    print("\n" + "=" * 60)
    print("  DONE")
